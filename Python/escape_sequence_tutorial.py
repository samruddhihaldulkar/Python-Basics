'''
some escape sequences used in python:
1. \n -> new line
2. \t -> horizontal tab
3. \" -> for printing double quotation
4. \' -> for printing single quotation
5. \r -> move the cursor to the beginning of the current line
6. \\ -> used for printing backslash
7. \0 -> represents the end of string
8. \f -> advance to the next page
9. \v -> vertical tab
10. \b -> move the cursor one position backwards
'''

print("Hello world, \nThis is a simple python program.\n\n")
print("Hello world, \tThis is a simple python program.\n\n")
print("Hello world, \rThis is a simple python program.\n\n")
print("Hello world, \vThis is a simple python program.\n\n")
print("Hello world, \bThis is a simple python program.\n\n")
print("Hello world, \fThis is a simple python program.\n\n")
print("Hello world, \'This is a simple python program.\'\n\n")
print("Hello world, \"This is a simple python program.\"\n\n")
print("Hello world, \\This is a simple python program.\n\n")
print("Hello world, \0This is a simple python program.\n\n")