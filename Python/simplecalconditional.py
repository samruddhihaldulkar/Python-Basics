num1=int(input("Enter a number: "))
num2=int(input("Enter a number: "))
ope=input("Enter a operator: ")
if ope=="+":
    print("sum is : ",num1+num2)
elif ope=="-":
    print("sub  is : ",num1-num2)
elif ope=="*":
    print("mul is : ",num1*num2)
elif ope=="/":
    print("div is : ",num1/num2)
